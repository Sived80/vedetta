def write_if_changed(path, data, binary=False):
    mode = "wb" if binary else "w"
    if path.exists():
        old = path.read_bytes()
        new = data if binary else data.encode("utf-8")
        if old == new:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    if binary:
        path.write_bytes(data)
    else:
        path.write_text(data, encoding="utf-8", newline="\n")
    return True


def main():
    si_hex = {}
    raw = try_fetch(SI_DATA)
    if raw:
        for ic in json.loads(raw.decode("utf-8")):
            si_hex[ic.get("slug") or ""] = ic.get("hex")
            # slug is not always present in older data; fall back to title
            title = re.sub(r"[^a-z0-9]", "", ic.get("title", "").lower())
            si_hex.setdefault(title, ic.get("hex"))
    else:
        print("WARNING: Simple Icons metadata not reachable; colours will be null")
    di_meta = {}
    raw = try_fetch(DI_META)
    if raw:
        di_meta = json.loads(raw.decode("utf-8"))

    logos, downloaded, missing, discarded, big = [], [], [], [], []
    for bid, names, kind, cands in BRANDS:
        svg, colour, src, why = None, None, None, None
        for slug in cands:
            if kind == "di" and di_meta and di_meta.get(slug, {}).get("base") not in (None, "svg"):
                why = "Dashboard Icons has only a %s version (no SVG)" % di_meta[slug].get("base")
                continue
            data = try_fetch((SI_ICON if kind == "si" else DI_ICON).format(slug))
            if data is None:
                why = why or "not found (tried: %s)" % ", ".join(cands)
                continue
            try:
                svg, dom = clean_svg(data, kind == "si", keep_full_size=bid in KEEP_FULL_SIZE)
            except Discard as e:
                discarded.append((bid, str(e)))
                svg = None
                why = None
                break
            src = "%s:%s" % (kind, slug)
            if kind == "si":
                h = si_hex.get(slug)
                colour = ("#" + h.upper()) if h else None
            else:
                colour = dom.upper() if dom else None
            break
        else:
            pass
        if svg is None:
            if why:
                missing.append((bid, why))
            continue
        size = len(svg.encode("utf-8"))
        if size > MAX_BYTES:
            big.append((bid, size))
            discarded.append((bid, "larger than %d KB (%d bytes)" % (MAX_BYTES // 1024, size)))
            continue
        write_if_changed(LOGO_DIR / (bid + ".svg"), svg)
        logos.append({"id": bid, "names": names, "source": src, "color": colour})
        downloaded.append(bid)

    # remove stale files of ids that are not in the catalogue any more
    keep = {l["id"] + ".svg" for l in logos}
    if LOGO_DIR.exists():
        for f in LOGO_DIR.glob("*.svg"):
            if f.name not in keep:
                f.unlink()

    doc = {"schema": 1, "_comment": COMMENT, "sources": SOURCES, "logos": logos}
    write_if_changed(JSON_PATH, json.dumps(doc, indent=1, ensure_ascii=False) + "\n")

    print("Downloaded: %d (si: %d, di: %d)" % (
        len(logos), sum(l["source"].startswith("si:") for l in logos),
        sum(l["source"].startswith("di:") for l in logos)))
    print("Missing:    %d" % len(missing))
    for b, w in missing:
        print("  - %s: %s" % (b, w))
    print("Discarded:  %d" % len(discarded))
    for b, w in discarded:
        print("  - %s: %s" % (b, w))
    return 0


if __name__ == "__main__":
    sys.exit(main())
