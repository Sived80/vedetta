# colour helpers
# --------------------------------------------------------------------------
NAMED = {"white": "#ffffff", "black": "#000000"}


def norm_color(c):
    """Return '#rrggbb', or None for none/url()/unknown/currentColor."""
    if not c:
        return None
    c = c.strip().lower()
    c = NAMED.get(c, c)
    m = re.fullmatch(r"#([0-9a-f]{3})", c)
    if m:
        return "#" + "".join(ch * 2 for ch in m.group(1))
    if re.fullmatch(r"#[0-9a-f]{6}", c):
        return c
    m = re.fullmatch(r"rgb\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)\s*\)", c)
    if m:
        return "#%02x%02x%02x" % tuple(min(255, int(x)) for x in m.groups())
    return None


def is_white(c):
    return c is not None and all(int(c[i:i + 2], 16) >= 0xF0 for i in (1, 3, 5))


def is_blackish(c):
    return c is not None and all(int(c[i:i + 2], 16) <= 0x20 for i in (1, 3, 5))


def local(tag):
    return tag.rsplit("}", 1)[-1]


def style_props(el):
    props = {}
    for part in (el.get("style") or "").split(";"):
        if ":" in part:
            k, v = part.split(":", 1)
            props[k.strip().lower()] = v.strip()
    return props


def paint(el, name):
    """Own value of a paint property (attribute or inline style)."""
    sp = style_props(el)
    return sp.get(name, el.get(name))


def css_fills(root):
    """Very small CSS reader for <style> blocks: {class: fill}."""
    out = {}
    for st in root.iter():
        if local(st.tag) == "style" and st.text:
            for m in re.finditer(r"\.([\w-]+)\s*\{([^}]*)\}", st.text):
                f = re.search(r"fill\s*:\s*([^;}\s]+)", m.group(2))
                if f:
                    out[m.group(1)] = f.group(1)
    return out


def gradient_first_stop(root):
    """{gradient id: first stop colour}"""
    out = {}
    for g in root.iter():
        if local(g.tag) in ("linearGradient", "radialGradient") and g.get("id"):
            for s in g.iter():
                if local(s.tag) == "stop":
                    c = norm_color(paint(s, "stop-color"))
                    if c:
                        out[g.get("id")] = c
                        break
    return out


