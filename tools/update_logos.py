"""Download, clean and catalogue the brand logos shown in the app.

What it does
------------
* Holds the STARTING LIST of brands (``BRANDS`` below): id, accepted names and
  the source slug(s) to try.
* Downloads each logo from jsDelivr:
    - Simple Icons  (CC0-1.0)     -> preferred whenever the logo exists there
    - Dashboard Icons (Apache-2.0) -> only for brands missing from Simple Icons
* Cleans every SVG down to a monochrome silhouette:
  ``<svg xmlns=... viewBox=...>`` plus <path>/<polygon>/<rect>/<circle>/... only.
  No <title>, <style>, <script>, <defs>, width/height, class, style, fill,
  stroke or any colour: the page colours the logo (CSS mask-image).
* Discards logos that would render badly (full-size background shape, nothing
  left after cleaning, too big) and reports them.
* Writes:
    vedetta/app/static/ha/logos/<id>.svg
    vedetta/app/data/brand_logos.json

The script is idempotent: it can be re-run at any time; files are rewritten
only when their content changes, and stale files of ids no longer in the
resulting catalogue are removed.  Only the standard library is used.
Network access is required.

Usage:  python tools/update_logos.py
"""
