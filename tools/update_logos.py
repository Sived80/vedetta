SVG_NS = "http://www.w3.org/2000/svg"
SHAPES = {"path", "polygon", "polyline", "rect", "circle", "ellipse"}
# attributes kept on shape elements (geometry only, no colour/style)
GEOM_ATTRS = {
    "path": ["d"], "polygon": ["points"], "polyline": ["points"],
    "rect": ["x", "y", "width", "height", "rx", "ry"],
    "circle": ["cx", "cy", "r"], "ellipse": ["cx", "cy", "rx", "ry"],
}
FILL_RULE_ATTRS = ["fill-rule", "clip-rule"]


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "vedetta-update-logos"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def try_fetch(url):
    try:
        return fetch(url)
    except (urllib.error.URLError, OSError):
        return None


