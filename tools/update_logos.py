# cleaning
# --------------------------------------------------------------------------
class Discard(Exception):
    pass


def fmt(n):
    s = ("%.3f" % n).rstrip("0").rstrip(".")
    return s or "0"


def parse_viewbox(root):
    vb = root.get("viewBox")
    if vb:
        nums = [float(x) for x in re.split(r"[ ,]+", vb.strip())]
        if len(nums) == 4:
            return nums
    w = re.sub(r"[a-z%]+$", "", (root.get("width") or "").strip())
    h = re.sub(r"[a-z%]+$", "", (root.get("height") or "").strip())
    if w and h:
        return [0.0, 0.0, float(w), float(h)]
    raise Discard("no viewBox")


def covers_viewbox(el, vb):
    """True if a rect/circle/ellipse fills (nearly) the whole viewBox."""
    t = local(el.tag)
    x0, y0, w, h = vb
    try:
        if t == "rect":
            ew = float(el.get("width", 0)); eh = float(el.get("height", 0))
            ex = float(el.get("x", 0)); ey = float(el.get("y", 0))
            return ew >= 0.9 * w and eh >= 0.9 * h and ex <= x0 + 0.05 * w and ey <= y0 + 0.05 * h
        if t == "circle":
            return float(el.get("r", 0)) * 2 >= 0.9 * min(w, h)
        if t == "ellipse":
            return float(el.get("rx", 0)) * 2 >= 0.9 * w and float(el.get("ry", 0)) * 2 >= 0.9 * h
    except ValueError:
        pass
    return False


def path_bbox_covers(el, vb):
    """Heuristic for a background <path> (rounded square / circle):
    bounding box of its absolute coordinates spans nearly the whole viewBox
    AND the path has few commands."""
    d = el.get("d", "")
    if len(re.findall(r"[A-Za-z]", d)) > 14:
        return False
    # only trust absolute-coordinate paths
    if re.search(r"[mlhvcsqtaz]", d.replace("e", "")) and not re.search(r"[MLHVCSQTAZ]", d):
        return False
    nums = [float(n) for n in re.findall(r"-?\d*\.?\d+(?:e-?\d+)?", d)]
    if len(nums) < 4:
        return False
    xs, ys = nums[0::2], nums[1::2]
    x0, y0, w, h = vb
    return (max(xs) - min(xs) >= 0.95 * w) and (max(ys) - min(ys) >= 0.95 * h)


def clean_svg(raw, is_simple_icons, keep_full_size=False):
    """Return (clean_svg_text, dominant_colour_or_None). Raises Discard."""
    text = raw.decode("utf-8", "replace")
    text = re.sub(r"<!DOCTYPE[^>]*>|<\?xml[^>]*\?>|<!--.*?-->", "", text, flags=re.S)
    try:
        root = ET.fromstring(text)
    except ET.ParseError as e:
        raise Discard("unparseable SVG (%s)" % e)
    if local(root.tag) != "svg":
        raise Discard("not an SVG")
    vb = parse_viewbox(root)
    classes = css_fills(root)
    grads = gradient_first_stop(root)
    kept = []
    colours = []
    dropped_white = 0

    def eff_fill(el, inherited):
        f = paint(el, "fill")
        if f is None and el.get("class"):
            for cl in el.get("class").split():
                if cl in classes:
                    f = classes[cl]
        return inherited if f is None else f

    def walk(el, inherited_fill, tf):
        nonlocal dropped_white
        t = local(el.tag)
        if t in ("defs", "style", "script", "title", "desc", "metadata",
                 "clipPath", "mask", "linearGradient", "radialGradient",
                 "filter", "pattern", "image", "text", "symbol"):
            return
        fill = eff_fill(el, inherited_fill)
        own_tf = el.get("transform")
        cur_tf = (tf + " " + own_tf).strip() if own_tf else tf
        if t == "g":
            for ch in el:
                walk(ch, fill, cur_tf)
            return
        if t not in SHAPES:
            return
        if (paint(el, "display") or "").strip() == "none":
            return
        fl = (fill or "black").strip()
        if fl == "none":
            return  # stroke-only / invisible: cannot be a silhouette
        op = paint(el, "opacity") or paint(el, "fill-opacity")
        if op is not None and op.strip() not in ("1", "1.0"):
            try:
                if float(op) < 0.5:
                    return
            except ValueError:
                pass
        col = None
        m = re.fullmatch(r"url\(#?['\"]?([^)'\"]+)['\"]?\)", fl)
        if m:
            col = grads.get(m.group(1))
        else:
            col = norm_color(fl)
        if is_white(col):
            dropped_white += 1
            return
        if not is_simple_icons and not keep_full_size and (covers_viewbox(el, vb) or
                                    (t == "path" and path_bbox_covers(el, vb))):
            raise Discard("full-size background shape")
        if col and not is_blackish(col):
            colours.append(col)
        elif col is None and not m:
            colours.append(None)
        attrs = []
        for a in GEOM_ATTRS[t]:
            if el.get(a) is not None:
                attrs.append('%s="%s"' % (a, re.sub(r"\s+", " ", el.get(a).strip())))
        for a in FILL_RULE_ATTRS:
            v = paint(el, a)
            if v:
                attrs.append('%s="%s"' % (a, v))
        if cur_tf:
            attrs.append('transform="%s"' % cur_tf)
        if not any(a.startswith(GEOM_ATTRS[t][0] + "=") for a in attrs):
            return
        kept.append("<%s %s/>" % (t, " ".join(attrs)))

    for ch in root:
        walk(ch, None, "")
    if not kept:
        raise Discard("nothing left after cleaning")
    vbs = " ".join(fmt(n) for n in vb)
    out = '<svg xmlns="%s" viewBox="%s">%s</svg>\n' % (SVG_NS, vbs, "".join(kept))
    dom = None
    for c in colours:
        if c:
            dom = c
            break
    return out, dom


